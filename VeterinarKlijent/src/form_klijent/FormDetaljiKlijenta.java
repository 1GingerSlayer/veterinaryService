    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed

        int result = JOptionPane.showConfirmDialog(this, "Da li ste sigurni da zelite da "
                + "obrisete ovog klijenta?", "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }

        if (result == JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().deleteKlijent(klijent);
                FormPretragaKlijenta fp = (FormPretragaKlijenta) getParent();
                fp.refreshTable();
                JOptionPane.showMessageDialog(this, "Sistem je obrisao klijenta.");
                this.dispose();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Ne mozete da obrisete ovog klijenta "
                        + "jer je imao termine!");
//                Logger.getLogger(FormDetaljiKlijenta.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed

        try {
            if (txtIme.getText().isEmpty() || txtPrezime.getText().isEmpty()
                    || txtEmail.getText().isEmpty()
                    || txtTelefon.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }

            String email = txtEmail.getText();
            String telefon = txtTelefon.getText();
            KategorijaKlijenta kategorijaKlijenta = (KategorijaKlijenta) cmbKategorijaKlijenta.getSelectedItem();

            klijent.setEmail(email);
            klijent.setTelefon(telefon);
            klijent.setKategorijaKlijenta(kategorijaKlijenta);

            ClientController.getInstance().updateKlijent(klijent);
            FormPretragaKlijenta fp = (FormPretragaKlijenta) getParent();
            fp.refreshTable();
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio klijenta.");
            this.dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
//            Logger.getLogger(FormDetaljiKlijenta.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnIzmeniActionPerformed


