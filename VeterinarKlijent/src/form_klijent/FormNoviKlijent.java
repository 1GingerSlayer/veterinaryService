    private void popuniKategorijeKlijenata() {
        try {
            ArrayList<KategorijaKlijenta> kategorijeKlijenta = ClientController.getInstance()
                    .getAllKategorijaKlijenta(new KategorijaKlijenta(-1, ""));

            cmbKategorijaKlijenta.removeAllItems();

            for (KategorijaKlijenta kategorijaKlijenta : kategorijeKlijenta) {
                cmbKategorijaKlijenta.addItem(kategorijaKlijenta);
            }
        } catch (Exception ex) {
            Logger.getLogger(FormNoviKlijent.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
