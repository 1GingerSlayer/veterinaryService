    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed

        int row = tblKlijenti.getSelectedRow();

        if (row >= 0) {
            try {
                Klijent izabraniKlijent
                        = ((TableModelKlijenti) tblKlijenti
                                .getModel()).getSelectedKlijent(row);

                //vracam klijente iz baze koja ce da ima tog izabranog klijenta
                ArrayList<Klijent> klijentIzBaze
                        = ClientController.getInstance().getAllKlijent(izabraniKlijent);

                JOptionPane.showMessageDialog(this, "Sistem je nasao klijenta!");

                //vracam listu sa tim jednim klijentom, zato klijentIzBaze.get(0)
                new FormDetaljiKlijenta(this, true, klijentIzBaze.get(0)).setVisible(true);

            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje klijenta!",
                        "Obavestenje", JOptionPane.ERROR_MESSAGE);
                Logger.getLogger(FormDetaljiKlijenta.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }//GEN-LAST:event_btnDetaljiActionPerformed

    private void txtImeKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtImeKeyReleased
        String ime = txtIme.getText();
        TableModelKlijenti tm = (TableModelKlijenti) tblKlijenti.getModel();
        tm.setParametarIme(ime);

        if (tm.getLista().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Sistem ne moze da nadje klijente po zadatim kriterijumima!",
                    "Obavestenje", JOptionPane.ERROR_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this,
                    "Sistem je nasao klijente po zadatim kriterijumima!");
        }
    }//GEN-LAST:event_txtImeKeyReleased

