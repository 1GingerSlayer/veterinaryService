    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed

        int result = JOptionPane.showConfirmDialog(this, "Da li ste sigurni da zelite da "
                + "obrisete ovaj termin?", "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }

        if (result == JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().deleteTermin(t);
                FormPretragaTermina fp = (FormPretragaTermina) getParent();
                fp.refreshTable();
                JOptionPane.showMessageDialog(this, "Uspesno obrisan termin.");
                this.dispose();
            } catch (Exception ex) {
                Logger.getLogger(FormDetaljiTermina.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed

        try {

            if (txtDatumVremePocetka.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Morate uneti datum pocetka i opis!");
                return;
            }

            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy HH:mm");
            Date datumVremePocetka = sdf.parse(txtDatumVremePocetka.getText());

            TableModelStavkeTermina tm = (TableModelStavkeTermina) tblStavke.getModel();

            t.setDatumVremePocetka(datumVremePocetka);
            t.setIznosBezPopusta(iznosBezPopusta);
            t.setKonacanIznos(iznosBezPopusta * (1 - (popust / 100)));
            t.setStavkeTermina(tm.getLista());

            ClientController.getInstance().updateTermin(t);
            FormPretragaTermina fp = (FormPretragaTermina) getParent();
            fp.refreshTable();
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio termin.");
            this.dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
            Logger.getLogger(FormDetaljiTermina.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnIzmeniActionPerformed

    private void btnDodajStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajStavkuActionPerformed

        Usluga u = (Usluga) cmbUsluga.getSelectedItem();
        String napomena = txtNapomena.getText();

        StavkaTermina st = new StavkaTermina(t, -1, u,
                napomena, u.getCena(), u.getCena());

        TableModelStavkeTermina tm = (TableModelStavkeTermina) tblStavke.getModel();

        if (tm.postojiUsluga(u)) {
            JOptionPane.showMessageDialog(this, "Vec ste uneli ovu uslugu za ovaj termin!");
            return;
        }

        tm.dodajStavku(st);

        iznosBezPopusta = tm.vratiUkupanIznos();
        txtIznosBezPopusta.setText(String.valueOf(iznosBezPopusta) + "din");

        if (txtIznosBezPopusta.getText().isEmpty()) {
            return;
        }

        if (klijent.getKategorijaKlijenta().getNaziv().equals("Standardni")) {
            popust = 0;
            txtPopust.setText("0%");
        }
        if (klijent.getKategorijaKlijenta().getNaziv().equals("Premium")) {
            popust = 10;
            txtPopust.setText("10%");
        }
        if (klijent.getKategorijaKlijenta().getNaziv().equals("VIP")) {
            popust = 20;
            txtPopust.setText("20%");
        }

        txtKonacanIznos.setText(iznosBezPopusta * (1 - (popust / 100)) + "din");
    }//GEN-LAST:event_btnDodajStavkuActionPerformed

