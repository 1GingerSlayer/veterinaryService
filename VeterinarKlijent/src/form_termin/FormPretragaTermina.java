    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed

        int row = tblTermini.getSelectedRow();

        if (row >= 0) {
            try {
                Termin izabraniTermin
                        = ((TableModelTermini) tblTermini
                                .getModel()).getSelectedTermin(row);
                ArrayList<Termin> terminIzBaze
                        = ClientController.getInstance().getAllTermin(izabraniTermin);

                JOptionPane.showMessageDialog(this, "Sistem je nasao termin!");
                new FormDetaljiTermina(this, true, terminIzBaze.get(0)).setVisible(true);
            } catch (Exception ex) {

                JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje termin!",
                        "Obavestenje", JOptionPane.ERROR_MESSAGE);
                Logger.getLogger(FormDetaljiTermina.class.getName()).log(Level.SEVERE, null, ex);
            }
        }


    }//GEN-LAST:event_btnDetaljiActionPerformed

    private void txtImeKlijentaKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtImeKlijentaKeyReleased
        String ime = txtImeKlijenta.getText();
        TableModelTermini tm = (TableModelTermini) tblTermini.getModel();
        tm.setParametarImeKlijenta(ime);

        if (tm.getLista().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Sistem ne moze da pronadje termine po zadatim vrednostima!",
                    "Obavestenje", JOptionPane.ERROR_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this,
                    "Sistem je pronasao termine po zadatim vrednostima!");
        }
    }//GEN-LAST:event_txtImeKlijentaKeyReleased

