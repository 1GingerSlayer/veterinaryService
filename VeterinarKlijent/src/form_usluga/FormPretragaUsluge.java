    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed

        int row = tblUsluge.getSelectedRow();

        if (row >= 0) {
            try {
                Usluga izabranaUsluga
                        = ((TableModelUsluge) tblUsluge
                                .getModel()).getSelectedUsluga(row);

                ArrayList<Usluga> uslugaIzBaze
                        = ClientController.getInstance().getAllUsluga(izabranaUsluga);

//                JOptionPane.showMessageDialog(this, "Sistem je nasao uslugu!");
                new FormDetaljiUsluge(this, true, uslugaIzBaze.get(0)).setVisible(true);

            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje uslugu!",
                        "Obavestenje", JOptionPane.ERROR_MESSAGE);
                Logger.getLogger(FormDetaljiUsluge.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }//GEN-LAST:event_btnDetaljiActionPerformed

