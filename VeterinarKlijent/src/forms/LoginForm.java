    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        try {
            if (txtUsername.getText().isEmpty()
                    || new String(txtPassword.getPassword()).isEmpty()) {
                JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra moraju "
                        + "biti popunjeni!");
                return;
            }

            Veterinar f = new Veterinar(-1, "", "", txtUsername.getText(),
                    new String(txtPassword.getPassword()));

            Veterinar veterinar = ClientController.getInstance().login(f);
            Session.getInstance().setUlogovani(veterinar);

            JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra su ispravni!");
            new MainForm().setVisible(true);
            this.dispose();

        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, "Server nije pokrenut!");
            System.exit(0);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Greska", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnLoginActionPerformed

